"""Build the hutch: the painted pen brought down to the scene's 224 x 92 art
pixels, its front rail as a layer of its own, and the straw the rabbits may
stand on. Dev-time only: `python scripts/make-hutch.py` (needs Pillow and NumPy).

The source picture (art/hutch/pen.png) is cut to the pen (`CROP`, source
pixels) and brought down to 224 art pixels wide by majority vote over a
64-colour palette, so its pixels are as crisp as the rabbits drawn on it.

The front rail and its posts (`FRONT`: the rows from the rail's top down, and
the posts rising above it) are also written alone, on a clear ground, to be
drawn over the rabbits so they stand inside the pen.

The ground is where a rabbit's feet may rest: the straw floor between the
back wall and the front rail (`GROUND`, a polygon in art pixels), off the
things standing on it (`SCENERY`: the hide box and the two bowls, with the
straw just behind them, where a rabbit would be drawn over them).
It is written to src/rendering/hutch-ground.js as rows of [x0, x1) runs.

Writes assets/hutch/pen.png, assets/hutch/pen-front.png and
src/rendering/hutch-ground.js. `--preview DIR` also writes the pen enlarged
with its ground tinted.
"""
import os
import sys
import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'art', 'hutch', 'pen.png')
OUT = os.path.join(ROOT, 'assets', 'hutch')
OUT_JS = os.path.join(ROOT, 'src', 'rendering', 'hutch-ground.js')
W, H = 224, 92

# the pen in the source picture: left, top, right, bottom
CROP = (9, 125, 1662, 804)

# the front rail: every row from RAIL_Y down, and the posts rising above it ([x0, y0, x1, y1], art pixels)
RAIL_Y = 76
POSTS = [(0, 68, 10, RAIL_Y), (55, 68, 65, RAIL_Y), (109, 68, 119, RAIL_Y), (163, 68, 173, RAIL_Y), (215, 68, 224, RAIL_Y)]

# the straw floor, between the back wall and the front rail (art pixels), kept
# half a rabbit in from the corner posts so none pokes through them
GROUND = [(18, 56), (208, 56), (208, 75), (18, 75)]

# what stands on the straw, [x0, y0, x1, y1]: no foot rests in it
SCENERY = [
    (156, 0, 224, 64),  # the hide box, and the straw beside it where a rabbit would overlap it
    (45, 57, 74, 71),   # the water bowl, and the straw just behind it
    (73, 63, 102, 77),  # the food bowl
]


def down(src, w, colours=64):
    """Majority vote over a palette, block by block, to w art pixels wide;
    a pixel is opaque when most of its block is."""
    sw, sh = src.size
    h = round(sh * w / sw)
    rgba = np.asarray(src.convert('RGBA'))
    q = src.convert('RGB').quantize(colours, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    idx, pal = np.asarray(q), q.getpalette()
    xs, ys = np.linspace(0, sw, w + 1).round().astype(int), np.linspace(0, sh, h + 1).round().astype(int)
    out = np.zeros((h, w, 4), np.uint8)
    for y in range(h):
        for x in range(w):
            a = rgba[ys[y]:ys[y + 1], xs[x]:xs[x + 1], 3] > 127
            if a.mean() < 0.5:
                continue
            i = np.bincount(idx[ys[y]:ys[y + 1], xs[x]:xs[x + 1]][a].ravel()).argmax()
            out[y, x, :3] = pal[i * 3:i * 3 + 3]
            out[y, x, 3] = 255
    return out


def ground():
    img = Image.new('L', (W, H), 0)
    d = ImageDraw.Draw(img)
    d.polygon(GROUND, fill=255)
    for x0, y0, x1, y1 in SCENERY:
        d.rectangle((x0, y0, x1 - 1, y1 - 1), fill=0)
    return np.asarray(img) > 0


def runs(row):
    out, x = [], 0
    while x < len(row):
        if row[x]:
            s = x
            while x < len(row) and row[x]:
                x += 1
            out.append([s, x])
        else:
            x += 1
    return out


def main():
    src = Image.open(SRC).crop(CROP)
    px = down(src, W)
    assert px.shape[:2] == (H, W), px.shape
    os.makedirs(OUT, exist_ok=True)
    Image.fromarray(px, 'RGBA').save(os.path.join(OUT, 'pen.png'), optimize=True)
    front = np.zeros_like(px)
    keep = np.zeros((H, W), bool)
    keep[RAIL_Y:, :] = True
    for x0, y0, x1, y1 in POSTS:
        keep[y0:y1, x0:x1] = True
    front[keep] = px[keep]
    Image.fromarray(front, 'RGBA').save(os.path.join(OUT, 'pen-front.png'), optimize=True)

    g = ground()
    rows = [runs(g[y]) for y in range(H)]
    y0 = next(y for y in range(H) if rows[y])
    y1 = max(y for y in range(H) if rows[y]) + 1
    body = ',\n'.join('  ' + str(rows[y]).replace(' ', '') for y in range(y0, y1))
    with open(OUT_JS, 'w') as f:
        f.write('// Generated by scripts/make-hutch.py — do not edit.\n')
        f.write('// The hutch\'s straw floor (assets/hutch/pen.png, 224 x 92): row by row from\n')
        f.write('// GROUND_Y0, the [x0, x1) runs a rabbit\'s feet may rest on.\n')
        f.write(f'export const GROUND_Y0 = {y0};\n')
        f.write(f'/** @type {{number[][][]}} */\nexport const GROUND = [\n{body},\n];\n')

    if len(sys.argv) > 2 and sys.argv[1] == '--preview':
        os.makedirs(sys.argv[2], exist_ok=True)
        im = px.astype(float)
        im[g, 0] = im[g, 0] * 0.5
        im[g, 1] = im[g, 1] * 0.5 + 127
        im[g, 2] = im[g, 2] * 0.5
        im[keep & (front[..., 3] > 0), 2] = 255
        big = Image.fromarray(im.clip(0, 255).astype(np.uint8), 'RGBA').resize((W * 6, H * 6), Image.NEAREST)
        d = ImageDraw.Draw(big)
        for x in range(0, W, 10):
            d.line((x * 6, 0, x * 6, H * 6), fill=(255, 0, 0, 90))
        for y in range(0, H, 10):
            d.line((0, y * 6, W * 6, y * 6), fill=(255, 0, 0, 90))
        big.save(os.path.join(sys.argv[2], 'hutch.png'))


if __name__ == '__main__':
    main()
