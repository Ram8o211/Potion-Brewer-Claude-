UNIT = 100
ASC = 7
DESC = 2

def build(out):
    order = ['.notdef'] + [f'u{ord(c):04X}' for c in G]
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    cmap = {ord(c): f'u{ord(c):04X}' for c in G}
    fb.setupCharacterMap(cmap)
    glyphs = {}
    metrics = {}
    pen = TTGlyphPen(None)
    pen.moveTo((100, 0)); pen.lineTo((100, 700)); pen.lineTo((500, 700)); pen.lineTo((500, 0)); pen.closePath()
    glyphs['.notdef'] = pen.glyph()
    metrics['.notdef'] = (600, 100)
    for ch, rows in G.items():
        name = f'u{ord(ch):04X}'
        w = max(len(r) for r in rows)
        pen = TTGlyphPen(None)
        for ri, row in enumerate(rows):
            # row 0 top (y = 6..7 px above baseline), row 6 baseline row, rows 7-8 below baseline
            y0 = (ASC - 1 - ri) * UNIT
            ci = 0
            while ci < len(row):
                if row[ci] != '#':
                    ci += 1
                    continue
                start = ci
                while ci < len(row) and row[ci] == '#':
                    ci += 1
                # one rectangle per horizontal run (fewer seams when scaled)
                x0, x1 = start * UNIT, ci * UNIT
                pen.moveTo((x0, y0))
                pen.lineTo((x0, y0 + UNIT))
                pen.lineTo((x1, y0 + UNIT))
                pen.lineTo((x1, y0))
                pen.closePath()
        glyphs[name] = pen.glyph()
        adv = (w + 1) * UNIT if ch != ' ' else 4 * UNIT
        metrics[name] = (adv, 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=900, descent=-300)
    fb.setupNameTable({'familyName': 'Alchemist Pixel', 'styleName': 'Regular', 'uniqueFontIdentifier': 'AlchemistPixel-Regular', 'fullName': 'Alchemist Pixel', 'psName': 'AlchemistPixel-Regular', 'version': '1.0', 'copyright': 'Original font made for The Alchemist’s Shop'})
    fb.setupOS2(sTypoAscender=900, sTypoDescender=-300, sTypoLineGap=100, usWinAscent=900, usWinDescent=300, sxHeight=500, sCapHeight=700)
    fb.setupPost()
    fb.save(out)
    print('wrote', out, len(G), 'glyphs')

if __name__ == '__main__':
    build(sys.argv[1] if len(sys.argv) > 1 else 'assets/fonts/alchemist-pixel.ttf')
