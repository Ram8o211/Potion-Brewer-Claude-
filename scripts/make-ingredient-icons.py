"""Build the ingredient icon sheet from the hand-picked icon art.
Dev-time only: `python scripts/make-ingredient-icons.py` (needs Pillow and NumPy).

art/icons/ingredients_sheet.png holds one painted icon per wild ingredient on
a transparent sheet, in rows. Each icon is found by its opaque pixels (rows,
then icons within a row, split at transparent gaps), matched to its
ingredient by reading order (KEYS), fitted into a CELL px square (centred,
aspect kept, smooth resampling: the art is detailed, not on a coarse pixel
grid) and packed into a COLS-wide grid, snapped to 256 colours.

Writes assets/icons/ingredients.png and src/rendering/ingredient-icons.js
(the frame rectangles).
"""
import os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'art', 'icons', 'ingredients_sheet.png')
OUT = os.path.join(ROOT, 'assets', 'icons', 'ingredients.png')
JS = os.path.join(ROOT, 'src', 'rendering', 'ingredient-icons.js')
CELL, PAD, COLS = 96, 3, 6

# the sheet's icons in reading order (materials/wild.js keys)
KEYS = [
    'ironroot', 'silverleaf', 'nightshade', 'emberbark', 'owlberry', 'witchear', 'mandrake',
    'heartpetal', 'sunthistle', 'nettle', 'dreamclover', 'sulfur', 'lodestone', 'cinnabar',
    'emberflint', 'mica', 'saltpetre', 'willowbark', 'reedmace', 'riverpearl',
    'riverchalk', 'frostcap', 'bogbean', 'beebalm', 'hemlock', 'ashbloom', 'obsidian',
    'dragonpepper', 'cinderscale', 'moonlily', 'toadstool', 'sirenreed', 'gravemoss', 'starquartz',
    'wisplichen', 'stormglass',
]


def runs(v, gap):
    idx = np.where(v)[0]
    out, s, p = [], idx[0], idx[0]
    for i in idx[1:]:
        if i - p > gap:
            out.append((s, p + 1))
            s = i
        p = i
    out.append((s, p + 1))
    return out


def icons(img):
    a = np.array(img)
    m = a[..., 3] > 40
    boxes = []
    for y0, y1 in runs(m.sum(1) > 0, 8):
        for x0, x1 in runs(m[y0:y1].sum(0) > 0, 8):
            ys = np.where(m[y0:y1, x0:x1].sum(1) > 0)[0]
            if (x1 - x0) * (ys[-1] - ys[0]) < 1500:
                continue  # a stray speck
            boxes.append((int(x0), int(y0 + ys[0]), int(x1), int(y0 + ys[-1] + 1)))
    return boxes


def main():
    img = Image.open(SRC).convert('RGBA')
    boxes = icons(img)
    assert len(boxes) == len(KEYS), f'{len(boxes)} icons on the sheet, {len(KEYS)} keys'
    rows = (len(KEYS) + COLS - 1) // COLS
    sheet = Image.new('RGBA', (COLS * CELL, rows * CELL), (0, 0, 0, 0))
    frames = {}
    for n, (key, (x0, y0, x1, y1)) in enumerate(zip(KEYS, boxes)):
        icon = img.crop((x0, y0, x1, y1))
        k = (CELL - 2 * PAD) / max(icon.size)
        icon = icon.resize((max(1, round(icon.width * k)), max(1, round(icon.height * k))), Image.LANCZOS)
        cx, cy = (n % COLS) * CELL, (n // COLS) * CELL
        sheet.alpha_composite(icon, (cx + (CELL - icon.width) // 2, cy + (CELL - icon.height) // 2))
        frames[key] = (cx, cy, CELL, CELL)
    # 256 colours keep the sheet small (a fifth of the size) with no visible loss
    sheet.quantize(256, method=Image.FASTOCTREE, dither=Image.Dither.NONE).save(OUT, optimize=True)
    lines = [
        '// Generated by scripts/make-ingredient-icons.py from art/icons/ — do not edit.',
        '// Frame rectangles [x, y, w, h] of each wild ingredient\'s icon in ICONS_URL.',
        '',
        "export const ICONS_URL = 'assets/icons/ingredients.png';",
        f'export const ICONS_SIZE = /** @type {{[number, number]}} */ ([{sheet.width}, {sheet.height}]);',
        '/** @type {Record<string, [number, number, number, number]>} */',
        'export const ICON_FRAMES = {',
        *[f'  {k}: [{x}, {y}, {w}, {h}],' for k, (x, y, w, h) in sorted(frames.items())],
        '};',
        '',
    ]
    with open(JS, 'w') as f:
        f.write('\n'.join(lines))
    print(f'wrote {OUT} ({sheet.width}x{sheet.height}) and {JS}')


if __name__ == '__main__':
    main()
